export type TranslationKey = keyof typeof DICTIONARY['en'];

export function getTranslation(lang: Language, key: TranslationKey, fallback?: string): string {
  const dict = DICTIONARY[lang] || DICTIONARY['en'];
  return (dict as any)[key] || fallback || key;
}

/**
 * Convert standard numerals to Bengali digits if desired
 */
export function toBengaliNumerals(input: string | number): string {
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(input).replace(/[0-9]/g, (digit) => bnDigits[parseInt(digit, 10)]);
}
